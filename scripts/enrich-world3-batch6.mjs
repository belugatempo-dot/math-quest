// ─── Apply enrichment ────────────────────────────────────────────
let added = 0;
for (const ch of world.chapters) {
  const map = ch.id === 'chapter-3-11' ? ch11NewProblems : ch.id === 'chapter-3-12' ? ch12NewProblems : null;
  if (!map) continue;

  for (const lv of ch.levels) {
    const extra = map[lv.id];
    if (extra) {
      lv.problems.push(...extra);
      lv.estimatedMinutes = Math.max(lv.estimatedMinutes || 2, lv.problems.length * 2);
      added += extra.length;
    }
  }

  if (ch.id === 'chapter-3-11') {
    ch.levels.push({ ...ch11Quiz, problems: ch11Quiz.problems });
    added += ch11Quiz.problems.length;
  }
  if (ch.id === 'chapter-3-12') {
    ch.levels.push({ ...ch12Quiz, problems: ch12Quiz.problems });
    ch.levels.push({ ...ch12Boss, problems: ch12Boss.problems });
    added += ch12Quiz.problems.length + ch12Boss.problems.length;
  }
}

