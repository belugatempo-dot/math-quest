function calcMinutes(problemCount, avgDifficulty) {
  const basePerProblem = avgDifficulty <= 2 ? 1.5 : avgDifficulty <= 3 ? 2 : 2.5;
  return Math.max(3, Math.round(problemCount * basePerProblem));
}

function enrichChapter(chapterIdx, newProblemsMap, quizLevel) {
  const chapter = world.chapters[chapterIdx];
  let added = 0;

  for (const level of chapter.levels) {
    const newProblems = newProblemsMap[level.id];
    if (newProblems && newProblems.length > 0) {
      level.problems.push(...newProblems);
      const totalProblems = level.problems.length;
      const avgDiff = level.problems.reduce((s, p) => s + p.difficulty, 0) / totalProblems;
      level.estimatedMinutes = calcMinutes(totalProblems, avgDiff);
      added += newProblems.length;
    }
  }

  chapter.levels.push(quizLevel);
  added += quizLevel.problems.length;

  console.log(`  ${chapter.name}: added ${added} problems across ${Object.keys(newProblemsMap).length + 1} levels (including quiz)`);
  console.log(`  Total levels: ${chapter.levels.length}, Total problems: ${chapter.levels.reduce((s, l) => s + l.problems.length, 0)}`);
}

