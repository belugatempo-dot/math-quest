// Helper to create a problem object
function prob(id, levelId, seq, type, category, statement, inputType, correctAnswer, hints, solutionExplanation, teachingPoint, tags, difficulty, extras = {}) {
  return {
    id,
    levelId,
    sequence: seq,
    type,
    category,
    statement,
    inputType,
    correctAnswer,
    hints,
    solutionExplanation,
    teachingPoint,
    tags,
    difficulty,
    ...extras,
  };
}

// Helper to create hints triplet
function h(t1, t2, t3) {
  return [
    { tier: 1, cost: 0, text: t1, type: 'conceptual' },
    { tier: 2, cost: 1, text: t2, type: 'directional' },
    { tier: 3, cost: 2, text: t3, type: 'scaffolded' },
  ];
}

